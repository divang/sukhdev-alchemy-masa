create table if not exists public.product_prices (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id) on delete cascade,
  quantity_basis text not null check (quantity_basis in ('per_100g', 'pack')),
  quantity_value integer not null check (quantity_value > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  currency text not null default 'INR',
  version integer not null check (version > 0),
  valid_from timestamptz not null default now(),
  valid_until timestamptz,
  reason text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (product_id, version)
);

create index if not exists product_prices_product_id_idx on public.product_prices(product_id);
create index if not exists product_prices_active_idx on public.product_prices(product_id, valid_from desc);

create table if not exists public.product_discounts (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id) on delete cascade,
  discount_percent numeric(5,2) not null check (discount_percent >= 0 and discount_percent <= 100),
  discount_type text not null check (discount_type in ('permanent', 'seasonal', 'flash_sale')),
  active_from timestamptz not null default now(),
  expires_at timestamptz,
  version integer not null check (version > 0),
  reason text not null default 'No reason provided',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, version),
  check (
    (discount_type = 'permanent' and expires_at is null)
    or (discount_type in ('seasonal', 'flash_sale') and expires_at is not null and expires_at > active_from)
  )
);

create index if not exists product_discounts_product_id_idx on public.product_discounts(product_id);
create index if not exists product_discounts_active_idx on public.product_discounts(product_id, active_from desc);

