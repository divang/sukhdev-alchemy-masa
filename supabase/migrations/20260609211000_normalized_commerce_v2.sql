create or replace function public.get_current_product_discount(target_product_id text)
returns table (
  id bigint,
  discount_percent numeric,
  discount_type text,
  expires_at timestamptz,
  version integer
)
language sql
stable
set search_path = public
as $$
  select
    pd.id,
    pd.discount_percent,
    pd.discount_type,
    pd.expires_at,
    pd.version
  from public.product_discounts pd
  where pd.product_id = target_product_id
    and pd.active_from <= now()
    and (pd.expires_at is null or pd.expires_at > now())
  order by pd.version desc
  limit 1;
$$;

