  pack_grams integer not null check (pack_grams > 0),
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  line_subtotal numeric(12,2) not null check (line_subtotal >= 0),
  discount_amount numeric(10,2) not null default 0 check (discount_amount >= 0),
  discount_percent numeric(5,2) not null default 0 check (discount_percent >= 0 and discount_percent <= 100),
  discount_type text,
  discount_version_id bigint,
  shipping_allocated_amount numeric(10,2) not null default 0 check (shipping_allocated_amount >= 0),
  tax_percent numeric(5,2) not null default 0 check (tax_percent >= 0 and tax_percent <= 100),
  tax_amount numeric(10,2) not null default 0 check (tax_amount >= 0),
  line_total numeric(12,2) not null check (line_total >= 0),
  price_version_id bigint,
  price_version_number integer,
  legacy_item_ordinal integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

